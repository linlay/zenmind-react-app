const { withAppDelegate } = require('expo/config-plugins');

const CALL_MARKER = '// @generated by withLocalCacheBackupExclusion';
const CALL_SNIPPET = `${CALL_MARKER}
    excludeLocalCachesFromBackup()`;
const METHOD_SNIPPET = `  private func excludeLocalCachesFromBackup() {
    guard let documentsURL = FileManager.default.urls(for: .documentDirectory, in: .userDomainMask).first else {
      return
    }

    for directoryName in ["SQLite", "mmkv"] {
      var cacheURL = documentsURL.appendingPathComponent(directoryName, isDirectory: true)
      do {
        try FileManager.default.createDirectory(at: cacheURL, withIntermediateDirectories: true)
        var resourceValues = URLResourceValues()
        resourceValues.isExcludedFromBackup = true
        try cacheURL.setResourceValues(resourceValues)
      } catch {
#if DEBUG
        NSLog("Failed to exclude local cache from backup: %@", error.localizedDescription)
#endif
      }
    }
  }
`;

function addLocalCacheBackupExclusion(contents) {
  let next = contents;
  if (!next.includes(CALL_MARKER)) {
    const callAnchor = '    let delegate = ReactNativeDelegate()';
    if (!next.includes(callAnchor)) {
      throw new Error('Unable to locate AppDelegate launch anchor for cache backup exclusion');
    }
    next = next.replace(callAnchor, `${CALL_SNIPPET}\n\n${callAnchor}`);
  }
  if (!next.includes('private func excludeLocalCachesFromBackup()')) {
    const methodAnchor = '  // Linking API';
    if (!next.includes(methodAnchor)) {
      throw new Error('Unable to locate AppDelegate method anchor for cache backup exclusion');
    }
    next = next.replace(methodAnchor, `${METHOD_SNIPPET}\n${methodAnchor}`);
  }
  return next;
}

module.exports = function withLocalCacheBackupExclusion(config) {
  return withAppDelegate(config, (config) => {
    if (config.modResults.language !== 'swift') {
      throw new Error('Local cache backup exclusion requires a Swift AppDelegate');
    }
    config.modResults.contents = addLocalCacheBackupExclusion(config.modResults.contents);
    return config;
  });
};

module.exports.addLocalCacheBackupExclusion = addLocalCacheBackupExclusion;
